/**
 * Manual bulk generation — "write me N posts between these two dates".
 *
 * This is an ORCHESTRATION layer and deliberately nothing else. It owns exactly
 * three things:
 *
 *   1. planning the slots the requested posts are scheduled into,
 *   2. calling the existing single-post generator once per slot,
 *   3. reporting honestly on what came out.
 *
 * Everything that makes a generated post good happens inside `generateDraftPost`
 * and is reached here for free, one call at a time: access control, the
 * "Content source" resolution, the atomic feed-item reservation that guarantees
 * one post per article, angle/pattern/aspect rotation, Topic Memory, the
 * Jaccard and semantic duplicate gates, language resolution, the frozen origin
 * snapshot, image generation, the source-article image import, embedding,
 * calibration and the audit log. None of it is re-implemented, re-ordered, or
 * bypassed — a bulk post is indistinguishable from a post the user generated by
 * clicking five times, apart from carrying a batch id.
 *
 * That sequential, one-at-a-time shape is a requirement, not an oversight. The
 * reservation, the duplicate gates and the diversity rotation all read what the
 * PREVIOUS post committed; generating concurrently would let five posts claim
 * five articles while every one of them still measures itself against the same
 * pre-run history, which is precisely how a batch of near-identical posts gets
 * written.
 *
 * Bulk posts are MANUAL generations: every one is created as `draft` and waits
 * for a person, whatever the channel's automation mode says. That is inherited
 * rather than asserted — `generateDraftPost` never passes an `initialStatus`, so
 * generation defaults to `draft`, and only cron's separate auto-approve step
 * ever promotes anything.
 *
 * A batch may also carry a CONTENT MIX — how many of its posts each source
 * writes. That too is orchestration and not a second distribution engine: the
 * quotas are handed to `lib/scheduling/content-mix.ts`, the same module the
 * weekly scheduler asks "which source is due next", and each answer becomes an
 * ordinary manual content-source pick on the very next generate call. The mix
 * arrives with the request and is never written back — the company's saved mix
 * is configuration, a batch's mix is one instruction.
 *
 * Running N generations inside one HTTP request is the real operational cost of
 * that shape, so the loop runs under the same ambient request deadline the cron
 * pipelines use and stops cleanly when the budget runs out — see
 * BULK_SOFT_BUDGET_MS.
 */

