export interface BulkGeneratePostsInput {
  channel: string;
  numberOfPosts: number;
  /** Inclusive `YYYY-MM-DD`, a business-zone calendar day. Must not be in the past. */
  startDate: string;
  /** Inclusive `YYYY-MM-DD`, a business-zone calendar day. */
  endDate: string;
  /**
   * A user-authored schedule: which days carry how many posts, and the exact
   * time of each one.
   *
   * Absent means "spread them evenly", the default — the channel's posting
   * windows inside the period decide both the days and the times. When present,
   * the user has chosen everything: the counts must add up to `numberOfPosts`,
   * and each day's times are scheduled exactly as given, in the business zone.
   * The channel's windows are not consulted at all in that case — a time on the
   * user's screen that this service then moved would make the form's preview a
   * lie. Either way the range bounds which days are allowed.
   */
  customDistribution?: BulkCustomDay[];

  // ── Everything below is passed through to each single generation unchanged ──
  contentLanguage?: string;
  includeSourceLinkOverride?: boolean;
  autoGenerateImageOverride?: boolean;
  llmConfigId?: string;
  /** The form's "Content source" choice, applied identically to every post. */
  contentSource?: ManualContentSourceRef;
  /**
   * A per-batch content mix: how many of these posts each source writes.
   *
   * Absent means the batch behaves exactly as it always has — one content-source
   * choice applied to every post. Present, it REPLACES that choice: each slot is
   * generated from whichever quota is due next, so `contentSource` must be the
   * pooled default (or absent) or the request is refused rather than one of the
   * two silently winning.
   *
   * This is a copy of the company's saved mix, sized to this batch, and nothing
   * here writes back to it. The saved default is configuration; this is one
   * run's instruction.
   */
  sourceMix?: BulkSourceQuota[];
}

